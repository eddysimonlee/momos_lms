-- Momos LMS · Supabase PostgreSQL schema (lms-1)
-- 적용: Supabase 대시보드 → SQL Editor 에 이 파일 전체를 붙여 넣고 한 번 실행.
-- 실행 전에 아래 한 줄의 <LMS_APP_PASSWORD> 를 길고 임의의 비밀번호로 바꾼다 (여기 적어 두지 않는다).
-- 서버는 이 lms_app 계정으로만 접속한다 (Session pooler 5432, 사용자명 lms_app.<project-ref>).
-- 기존 테이블을 지우거나 바꾸지 않는다. 다시 실행하면 "already exists" 로 멈추는 것이 정상이다.

BEGIN;

CREATE ROLE lms_app LOGIN PASSWORD '<LMS_APP_PASSWORD>' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;

CREATE SCHEMA lms_workspace AUTHORIZATION postgres;
GRANT USAGE ON SCHEMA lms_workspace TO lms_app;
REVOKE ALL ON SCHEMA lms_workspace FROM PUBLIC, anon, authenticated;

SET search_path = lms_workspace, pg_catalog;

-- 업로드 파일(사진) 메타데이터. 실제 바이트는 비공개 Storage 버킷 uploads/<id>
CREATE TABLE files(id TEXT PRIMARY KEY,name TEXT,size INTEGER,sha256 TEXT,created TEXT);
-- 교육 기록 등 JSON 문서 (학습자별 Room, 루트 설정)
CREATE TABLE metadata(id BIGINT PRIMARY KEY,body TEXT);
-- 계정·세션·감사 (access.py)
CREATE TABLE access_users(
    id TEXT PRIMARY KEY,name TEXT UNIQUE NOT NULL,email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,salt TEXT NOT NULL,role TEXT NOT NULL,
    company TEXT NOT NULL,department TEXT NOT NULL,title TEXT NOT NULL,
    status TEXT NOT NULL,created_at DOUBLE PRECISION NOT NULL,updated_at DOUBLE PRECISION NOT NULL);
CREATE TABLE access_sessions(
    token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL,csrf TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL);
CREATE TABLE access_audit(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at DOUBLE PRECISION NOT NULL,actor_id TEXT,
    kind TEXT NOT NULL,target_id TEXT,detail TEXT NOT NULL);
CREATE TABLE file_access(
    file_id TEXT PRIMARY KEY,user_id TEXT NOT NULL,task_id TEXT NOT NULL);
CREATE TABLE access_recovery(
    token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL,
    account_version DOUBLE PRECISION NOT NULL,created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,used_at DOUBLE PRECISION);
CREATE TABLE access_reset_requests(
    user_id TEXT PRIMARY KEY,requested_at DOUBLE PRECISION NOT NULL,status TEXT NOT NULL);
-- 초대 링크 (invitations.py)
CREATE TABLE invitations(
    id TEXT PRIMARY KEY,email TEXT NOT NULL,name TEXT NOT NULL,company TEXT NOT NULL,
    role TEXT NOT NULL,department TEXT NOT NULL,token_hash TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL,created_by TEXT NOT NULL,created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,accepted_at DOUBLE PRECISION,delivery TEXT NOT NULL);
-- 스키마 버전 표시. 서버가 시작할 때 확인한다.
CREATE TABLE cloud_meta(id TEXT PRIMARY KEY,body TEXT NOT NULL);
INSERT INTO cloud_meta VALUES('schema_version','lms-1');

-- 모든 표: 앱 계정만, RLS 켬, anon/authenticated 차단
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA lms_workspace TO lms_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lms_workspace TO lms_app;
REVOKE ALL ON ALL TABLES IN SCHEMA lms_workspace FROM PUBLIC, anon, authenticated;

ALTER TABLE files ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON files FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE metadata ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON metadata FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE access_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON access_users FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE access_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON access_sessions FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE access_audit ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON access_audit FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE file_access ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON file_access FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE access_recovery ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON access_recovery FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE access_reset_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON access_reset_requests FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE invitations ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON invitations FOR ALL TO lms_app USING (true) WITH CHECK (true);
ALTER TABLE cloud_meta ENABLE ROW LEVEL SECURITY;
CREATE POLICY backend_only ON cloud_meta FOR ALL TO lms_app USING (true) WITH CHECK (true);

COMMIT;

